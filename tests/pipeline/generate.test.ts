import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { resolveConfig } from "../../scripts/config.ts";
import { AuthorError } from "../../scripts/errors.ts";
import {
  GENERATORS,
  envFileContents,
  generate,
  generateEnv,
  generateObjectsFiles,
  type Generator,
} from "../../scripts/generate.ts";
import {
  FIXTURE_MAP,
  FIXTURE_OBJECTS_MAP,
  linkNodeModules,
  makeTempDir,
} from "./helpers.ts";

const configIn = (root: string, mode: "dev" | "release" = "dev") =>
  resolveConfig({ mapFolder: "maps/m.w3x", mode }, root);

describe("envFileContents", () => {
  it("exports devMode true for dev and false for release, and nothing else", () => {
    expect(envFileContents("dev")).toMatch(
      /^\/\/ Generated by the build pipeline/,
    );
    expect(envFileContents("dev")).toContain(
      "export const devMode: boolean = true;\n",
    );
    expect(envFileContents("release")).toContain(
      "export const devMode: boolean = false;\n",
    );
    expect(envFileContents("release").match(/export /g)).toHaveLength(1);
  });
});

describe("generate", () => {
  it("creates the generated folder and writes the env file for the effective mode", () => {
    const root = makeTempDir();
    expect(generate(configIn(root, "release"), [generateEnv])).toEqual([
      path.join(root, "src", "generated", "env.ts"),
    ]);
    expect(
      fs.readFileSync(path.join(root, "src", "generated", "env.ts"), "utf8"),
    ).toBe(envFileContents("release"));
  });

  it("rewrites a file whose text changed and leaves an unchanged one alone", () => {
    const root = makeTempDir();
    const env = path.join(root, "src", "generated", "env.ts");
    generate(configIn(root, "dev"), [generateEnv]);
    const old = new Date(2000, 0, 1);
    fs.utimesSync(env, old, old);

    generate(configIn(root, "dev"), [generateEnv]);
    expect(fs.statSync(env).mtime).toEqual(old);

    generate(configIn(root, "release"), [generateEnv]);
    expect(fs.readFileSync(env, "utf8")).toBe(envFileContents("release"));
  });

  it("runs every writer it is given, in order", () => {
    const root = makeTempDir();
    const one: Generator = () => [{ name: "one.d.ts", contents: "1" }];
    const two: Generator = (config) => [
      { name: "two.lua", contents: config.mode },
    ];
    expect(
      generate(configIn(root), [one, two]).map((file) => path.basename(file)),
    ).toEqual(["one.d.ts", "two.lua"]);
    expect(
      fs.readFileSync(path.join(root, "src", "generated", "two.lua"), "utf8"),
    ).toBe("dev");
  });

  it("refuses a writer whose file name leaves the generated folder", () => {
    const escape: Generator = () => [{ name: "../main.ts", contents: "" }];
    expect(() => generate(configIn(makeTempDir()), [escape])).toThrow(
      /bare file name/,
    );
  });
});

describe("GENERATORS", () => {
  it("writes the env file, both editor-globals files and the map's objects from the map folder", () => {
    const root = makeTempDir();
    const files = generate(
      resolveConfig({ mapFolder: FIXTURE_MAP }, root),
      GENERATORS,
      () => undefined,
    );
    expect(files.map((file) => path.relative(root, file))).toEqual(
      [
        "env.ts",
        "editor-globals.d.ts",
        "editor-globals.lua",
        "map-objects.d.ts",
        "custom-units.ts",
        "custom-items.ts",
        "custom-abilities.ts",
        "custom-buffs.ts",
        "custom-destructables.ts",
        "custom-doodads.ts",
        "custom-upgrades.ts",
      ].map((name) => path.join("src", "generated", name)),
    );
  });

  it("writes an overload per Custom object and per modified Built-in object, and the Custom constants", () => {
    const root = makeTempDir();
    linkNodeModules(root);
    const warnings: string[] = [];
    generate(
      resolveConfig({ mapFolder: FIXTURE_OBJECTS_MAP }, root),
      GENERATORS,
      (message) => warnings.push(message),
    );
    expect(warnings).toEqual([]);
    const read = (name: string) =>
      fs.readFileSync(path.join(root, "src", "generated", name), "utf8");
    const overloads = read("map-objects.d.ts");
    expect(overloads).toContain(
      'declare function FourCC(id: "h000"): Rawcode<"unit">;',
    );
    // A modified Built-in object: its overload names the package's constant.
    expect(overloads).toContain(
      'declare function FourCC(id: "hfoo"): Rawcode<"unit">;',
    );
    // The base names come from reforged-builtins, resolved from the Map project.
    expect(overloads).toContain(
      "Captain (`h000`), a Custom unit of this map, derived from Footman (`hfoo`).",
    );
    expect(overloads).toContain("Its constant is `Units.Footman_hfoo`");
    expect(read("custom-units.ts")).toContain(
      'Captain_h000: 1747988528 as Rawcode<"unit">,',
    );
    expect(read("custom-units.ts")).not.toContain("Footman_hfoo");
    expect(read("custom-abilities.ts")).toContain("ArcticBlizzard_A000");
    // The Custom buff and the Custom destructable at B000: a constant each.
    expect(read("custom-buffs.ts")).toContain("HolyFire_B000");
    expect(read("custom-destructables.ts")).toContain("Gate_B000");
  });

  it("passes the editor-globals warnings to warn", () => {
    const root = makeTempDir();
    const map = path.join(root, "maps", "m.w3x");
    fs.mkdirSync(map, { recursive: true });
    fs.writeFileSync(
      path.join(map, "war3map.lua"),
      "gg_qst_Main = nil\nfunction InitGlobals()\nend\n",
    );
    const warnings: string[] = [];
    generate(configIn(root), GENERATORS, (message) => warnings.push(message));
    expect(warnings).toEqual([
      "gg_qst_Main: unknown editor prefix gg_qst_, declared as handle.",
    ]);
  });

  it("passes the objects' warnings to warn", () => {
    const root = makeTempDir();
    const map = path.join(root, "maps", "m.w3x");
    fs.mkdirSync(map, { recursive: true });
    fs.writeFileSync(path.join(map, "war3map.w3u"), "garbage");
    const warnings: string[] = [];
    generateObjectsFiles(configIn(root), (message) => warnings.push(message));
    expect(warnings).toEqual([
      "war3map.w3u not read (unknown format version 1651663207): its objects are left out. Save the map with the World Editor of 3.0.",
    ]);
  });

  it("writes the objects' files empty for a map folder without Object data", () => {
    const root = makeTempDir();
    fs.mkdirSync(path.join(root, "maps", "m.w3x"), { recursive: true });
    const files = generateObjectsFiles(configIn(root), () => undefined);
    expect(
      files.find((file) => file.name === "custom-units.ts")?.contents,
    ).toMatch(/export const CustomUnits = \{\s*\} as const;/);
  });

  it("includes the objects defined in code: a constant and an overload, named from the definition", () => {
    const root = makeTempDir();
    linkNodeModules(root);
    fs.mkdirSync(path.join(root, "src", "objects"), { recursive: true });
    fs.writeFileSync(
      path.join(root, "src", "objects", "units.ts"),
      `import { defineUnit } from "reforged-map/objects";\n\nexport const Sergeant = defineUnit({\n  rawcode: "h002",\n  base: FourCC("hfoo"),\n  fields: { unam: "Sergeant" },\n});\n`,
    );
    const files = generateObjectsFiles(
      resolveConfig({ mapFolder: FIXTURE_MAP }, root),
      () => undefined,
    );
    const read = (name: string) =>
      files.find((file) => file.name === name)?.contents ?? "";
    expect(read("custom-units.ts")).toContain(
      'Sergeant_h002: 1747988530 as Rawcode<"unit">,',
    );
    expect(read("map-objects.d.ts")).toContain(
      'declare function FourCC(id: "h002"): Rawcode<"unit">;',
    );
    expect(read("map-objects.d.ts")).toContain("src/objects/units.ts");
  });

  it("fails the objects with an author error on a definition that does not load", () => {
    const root = makeTempDir();
    linkNodeModules(root);
    fs.mkdirSync(path.join(root, "src", "objects"), { recursive: true });
    fs.writeFileSync(
      path.join(root, "src", "objects", "units.ts"),
      `import { defineUnit } from "reforged-map/objects";\n\nexport const Odd = defineUnit({ rawcode: "h002", base: FourCC("zzzz"), fields: {} });\n`,
    );
    const run = () =>
      generateObjectsFiles(
        resolveConfig({ mapFolder: FIXTURE_MAP }, root),
        () => undefined,
      );
    expect(run).toThrow(AuthorError);
    expect(run).toThrow(/units\.ts.*h002.*zzzz/);
  });

  it("fails the objects with an author error on a missing map folder", () => {
    const run = () =>
      generateObjectsFiles(configIn(makeTempDir()), () => undefined);
    expect(run).toThrow(AuthorError);
    expect(run).toThrow(
      /^Map folder not found: .*m\.w3x\. Save the map as a folder/,
    );
  });

  it("fails with an author error on a map folder without war3map.lua", () => {
    const root = makeTempDir();
    fs.mkdirSync(path.join(root, "maps", "m.w3x"), { recursive: true });
    const run = () => generate(configIn(root), GENERATORS, () => undefined);
    expect(run).toThrow(AuthorError);
    expect(run).toThrow(
      "m.w3x has no war3map.lua: the map was not saved with Lua as the script language. " +
        "In the World Editor, set Scenario > Map Options > Script Language to Lua and save the map again.",
    );
  });
});
